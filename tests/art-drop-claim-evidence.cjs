const { PGlite } = require('@electric-sql/pglite');
const { pgcrypto } = require('@electric-sql/pglite/contrib/pgcrypto');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const db = new PGlite({ extensions: { pgcrypto } });
  const root = path.join(__dirname, '..');
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema auth;
    create table auth.users (id uuid primary key);
    create table art_drop_control (id integer primary key, paused boolean);
    insert into art_drop_control values (1, false);
    create table engagement_sessions (
      session_hash text primary key, first_seen timestamptz not null,
      last_seen timestamptz not null, last_sponsor_click_at timestamptz,
      sponsor_auction_id text not null default '', updated_at timestamptz
    );
    create table art_drops (
      id uuid primary key default gen_random_uuid(), public_id text unique,
      claim_code text, code_hash text unique, reward_usdc numeric(12,2),
      status text, scheduled_for timestamptz, published_at timestamptz,
      expires_at timestamptz, reserved_at timestamptz, claim_wallet text default '',
      payout_signature text default '', payout_error text default '', paid_at timestamptz,
      created_at timestamptz default now(), updated_at timestamptz
    );
    create table auctions (
      id text primary key, sequence bigint unique, starts_at bigint,
      ends_at bigint, status text, created_at timestamptz default now()
    );
    create table bids (
      id bigint generated by default as identity primary key,
      auction_id text references auctions(id), wallet text not null,
      amount_usdc numeric(12,2) not null, quiet_balance numeric(30,9) default 0,
      quiet_balance_slot bigint default 0, bid_multiplier numeric(12,6) default 1,
      effective_bid_usdc numeric(24,8) not null, payment_status text default 'verified',
      payment_signature text, verification_provider text default 'solana-usdc',
      bid_source text default 'user', created_at timestamptz default now()
    );
    create table attention_events (
      id bigint generated by default as identity primary key,
      auction_id text references auctions(id), event_type text, wallet text default '',
      target_url text default '', event_source text default 'organic',
      created_at timestamptz default now()
    );
    create function reserve_art_drop(text, text) returns void language sql as 'select';
    create function reserve_art_drop(text, text, text, text) returns void language sql as 'select';
  `);

  const migration = readFileSync(
    path.join(root, 'database/credits-reports-and-art-drop-limits.sql'),
    'utf8'
  );
  await db.exec(migration);
  await db.exec(migration);
  assert.equal((await db.query(`select to_regprocedure('reserve_art_drop(text,text)') legacy`)).rows[0].legacy, null);
  assert.equal((await db.query(`select to_regprocedure('reserve_art_drop(text,text,text,text)') legacy`)).rows[0].legacy, null);

  let n = 0;
  async function seed({ sessionAge = '6 minutes', heartbeatAge = '0 minutes' } = {}) {
    n += 1;
    const code = `code-${n}`;
    const session = `session-${n}`;
    await db.query(
      `insert into art_drops (public_id,claim_code,code_hash,reward_usdc,status,scheduled_for,expires_at)
       values ($1,$1,$1,2,'active',now(),now()+interval '1 hour')`,
      [code]
    );
    await db.query(
      `insert into engagement_sessions
       (session_hash,first_seen,last_seen,last_sponsor_click_at,sponsor_auction_id)
       values ($1,now()-$2::interval,now()-$3::interval,null,'')`,
      [session, sessionAge, heartbeatAge]
    );
    return { code, session };
  }
  async function claim(drop, wallet = `wallet-${n}`, claimant = `claimant-${n}`) {
    return db.query(
      `select * from reserve_art_drop($1,$2,$3,$4,70)`,
      [drop.code, wallet, claimant, drop.session]
    );
  }

  const valid = await seed();
  const won = (await claim(valid)).rows[0];
  assert.equal(won.status, 'reserved');
  assert.equal(won.reward_usdc, '2.00');
  assert.equal(won.claim_engagement.version, 2);
  assert.equal(won.claim_engagement.click_required, false);
  assert.equal(won.claim_engagement.session_hash, valid.session);
  assert.ok(won.claim_engagement.elapsed_seconds >= 300);
  assert.equal(
    (await db.query(`select (claim_engagement->>'checked_at')::timestamptz = reserved_at same_time from art_drops where code_hash=$1`, [valid.code])).rows[0].same_time,
    true
  );

  const tooShort = await seed({ sessionAge: '4 minutes' });
  await assert.rejects(claim(tooShort), /engagement/);
  const inactive = await seed({ heartbeatAge: '3 minutes' });
  await assert.rejects(claim(inactive), /engagement/);

  const walletRepeat = await seed();
  await assert.rejects(claim(walletRepeat, 'wallet-1', 'new-claimant'), /rolling 24-hour/);
  const sessionRepeat = await seed();
  sessionRepeat.session = valid.session;
  await assert.rejects(claim(sessionRepeat, 'new-wallet', 'new-claimant-2'), /rolling 24-hour/);
  const claimantRepeat = await seed();
  await assert.rejects(claim(claimantRepeat, 'new-wallet-2', 'claimant-1'), /rolling 24-hour/);

  await db.exec(`
    insert into art_drops
      (public_id,claim_code,code_hash,reward_usdc,status,scheduled_for,reserved_at,claim_wallet,claimant_hash,engagement_session_hash)
    select 'budget-'||g, 'budget-'||g, 'budget-'||g, 2, 'reserved', now(), now(),
           'budget-wallet-'||g, 'budget-claimant-'||g, 'budget-session-'||g
    from generate_series(1,34) g
  `);
  const capped = await seed();
  await assert.rejects(claim(capped), /70 USDC daily/);

  const user = '00000000-0000-0000-0000-000000000001';
  await db.query(`insert into auth.users values ($1)`, [user]);
  await db.query(`insert into platform_credit_accounts (user_id,balance_credits) values ($1,10)`, [user]);
  await db.exec(`insert into auctions values ('attention-test',1,(extract(epoch from now())*1000)::bigint+60000,(extract(epoch from now())*1000)::bigint+1860000,'scheduled',now())`);
  const bidId = (await db.query(`select place_credit_bid($1,'attention-test',2.25) id`, [user])).rows[0].id;
  assert.ok(bidId);
  let account = (await db.query(`select * from platform_credit_accounts where user_id=$1`, [user])).rows[0];
  assert.equal(account.balance_credits, '7.75');
  assert.equal(account.reserved_credits, '0.00');
  await assert.rejects(
    db.query(`select place_credit_bid($1,'attention-test',2.50)`, [user]),
    /minimum credit bid/
  );

  const purchase = (await db.query(
    `insert into credit_purchases (user_id,amount_usd,credits,status,stripe_payment_intent_id)
     values ($1,5,5,'paid','pi_test') returning id`,
    [user]
  )).rows[0].id;
  await db.query(`update platform_credit_accounts set balance_credits=1 where user_id=$1`, [user]);
  await db.query(`select apply_credit_refund($1,5)`, [purchase]);
  account = (await db.query(`select * from platform_credit_accounts where user_id=$1`, [user])).rows[0];
  assert.equal(account.balance_credits, '0.00');
  assert.equal(account.deficit_credits, '4.00');
  assert.equal(account.status, 'frozen');
  const recovery = (await db.query(
    `insert into credit_purchases (user_id,amount_usd,credits,status)
     values ($1,5,5,'pending') returning id`,
    [user]
  )).rows[0].id;
  await db.query(`select settle_credit_purchase($1,'cs_test','pi_recovery')`, [recovery]);
  account = (await db.query(`select * from platform_credit_accounts where user_id=$1`, [user])).rows[0];
  assert.equal(account.balance_credits, '1.00');
  assert.equal(account.deficit_credits, '0.00');
  assert.equal(account.status, 'active');

  const grants = (await db.query(`
    select
      has_function_privilege('anon','reserve_art_drop(text,text,text,text,numeric)','execute') anon,
      has_function_privilege('authenticated','reserve_art_drop(text,text,text,text,numeric)','execute') authenticated,
      has_function_privilege('service_role','reserve_art_drop(text,text,text,text,numeric)','execute') service
  `)).rows[0];
  assert.deepEqual(grants, { anon: false, authenticated: false, service: true });
  await db.close();
  console.log('PASS: five-minute eligibility without click, atomic evidence, rolling cooldowns, 70 USDC cap, credit bid ledger, refund freeze, and grants');
})().catch((error) => { console.error(error); process.exit(1); });
