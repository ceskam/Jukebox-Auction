-- AdBidCoin sponsor packages, house-ad attribution, and Art Drop engagement gates.
-- Run once in the Supabase SQL editor before deploying the matching application code.

alter table public.attention_events
  add column if not exists event_source text not null default 'organic';

alter table public.attention_events
  drop constraint if exists attention_events_event_source_check;

alter table public.attention_events
  add constraint attention_events_event_source_check
  check (event_source in ('organic', 'house'));

create index if not exists attention_events_source_type_created_idx
  on public.attention_events (event_source, event_type, created_at desc);

create table if not exists public.payment_receipts (
  signature text primary key,
  purpose text not null check (purpose in ('bid', 'sponsor')),
  wallet text not null,
  amount_usdc numeric(12, 2) not null check (amount_usdc > 0),
  reference_key text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.engagement_sessions (
  session_hash text primary key,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  last_sponsor_click_at timestamptz,
  sponsor_auction_id text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists engagement_sessions_last_seen_idx
  on public.engagement_sessions (last_seen desc);

create table if not exists public.sponsor_orders (
  id uuid primary key default gen_random_uuid(),
  wallet text not null,
  plan_code text not null check (plan_code in ('starter', 'growth')),
  amount_usdc numeric(12, 2) not null check (amount_usdc in (200, 400)),
  minimum_placements integer not null check (minimum_placements in (20, 50)),
  sponsor_name text not null,
  title text not null,
  description text not null,
  url text not null,
  image_url text not null default '',
  contact text not null default '',
  status text not null default 'pending_review'
    check (status in ('pending_review', 'active', 'paused', 'rejected', 'completed', 'expired')),
  payment_signature text not null unique,
  starts_at timestamptz,
  ends_at timestamptz,
  last_featured_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);

create index if not exists sponsor_orders_rotation_idx
  on public.sponsor_orders (status, last_featured_at, ends_at);

create table if not exists public.sponsor_placements (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.sponsor_orders(id) on delete cascade,
  auction_id text not null unique references public.auctions(id) on delete restrict,
  channel text not null default 'homepage',
  status text not null default 'published'
    check (status in ('published', 'cancelled')),
  featured_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists sponsor_placements_order_status_idx
  on public.sponsor_placements (order_id, status, featured_at desc);

alter table public.engagement_sessions enable row level security;
alter table public.payment_receipts enable row level security;
alter table public.sponsor_orders enable row level security;
alter table public.sponsor_placements enable row level security;

revoke all on table public.engagement_sessions from anon, authenticated;
revoke all on table public.payment_receipts from anon, authenticated;
revoke all on table public.sponsor_orders from anon, authenticated;
revoke all on table public.sponsor_placements from anon, authenticated;

grant select, insert, update, delete on table public.engagement_sessions to service_role;
grant select, insert, update, delete on table public.payment_receipts to service_role;
grant select, insert, update, delete on table public.sponsor_orders to service_role;
grant select, insert, update, delete on table public.sponsor_placements to service_role;
grant usage, select on sequence public.sponsor_placements_id_seq to service_role;

comment on table public.engagement_sessions is
  'Hashed first-party sessions used to enforce active-time and sponsor-click Art Drop eligibility.';
comment on table public.payment_receipts is
  'Cross-product Solana receipt ledger preventing reuse between bids and sponsor packages.';
comment on table public.sponsor_orders is
  'Verified USDC automatic house-slot packages awaiting or passing editorial approval.';
comment on table public.sponsor_placements is
  'Auditable delivery ledger for paid and bonus sponsor features.';
